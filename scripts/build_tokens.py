"""Generate frontend/src/styles/tokens.css from design/tokens.json (single source of truth).

    python scripts/build_tokens.py           # write the CSS
    python scripts/build_tokens.py --check   # exit 1 if the committed CSS is stale
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "design" / "tokens.json"
OUT = ROOT / "frontend" / "src" / "styles" / "tokens.css"


def mode_vars(t: dict, mode: str) -> list[str]:
    c = t["color"][mode]
    s, st = c["status"], c["status_text"]
    rows = [
        ("color-bg", c["canvas"]),
        ("color-surface", c["surface"]),
        ("color-border", c["border"]),
        ("color-hover", c["hover"]),
        ("color-text", c["text"]),
        ("color-muted", c["text_muted"]),
        ("color-accent", c["brand_neuroroute"]),
        ("color-accent-text", c["accent_text"]),
        ("color-accent-soft", c["accent_wash"]),
        ("color-brand-netmind", c["brand_netmind"]),
        ("glass-bg", t["glass"][mode]),
        ("status-healthy", s["healthy"]),
        ("status-warning", s["warning"]),
        ("status-critical", s["critical"]),
        ("status-telemetry", s["telemetry"]),
        # text-safe status colors (AA contrast); components use these for text
        ("color-ok", st["healthy"]),
        ("color-warn", st["warning"]),
        ("color-error", st["critical"]),
        ("color-info", st["telemetry"]),
    ]
    return [f"  --{k}: {v};" for k, v in rows] + [f"  color-scheme: {mode};"]


def shared_vars(t: dict) -> list[str]:
    fam = t["text"]["family"]
    rows = [("glass-blur", t["glass"]["blur"]), ("font-sans", fam["sans"]), ("font-mono", fam["mono"]),
            ("font", "var(--font-sans)")]
    for name, ty in t["text"]["scale"].items():
        rows += [(f"type-{name}-size", ty["size"]), (f"type-{name}-line", ty["line"]),
                 (f"type-{name}-weight", ty["weight"]), (f"type-{name}-tracking", ty["tracking"]),
                 (f"type-{name}-family", f"var(--font-{ty['family']})")]
    rows += [(f"space-{k}", v) for k, v in t["spacing"].items()]
    rows += [("space", "var(--space-lg)")]
    rows += [(f"radius-{k}", v) for k, v in t["radii"].items()]
    rows += [("radius", "var(--radius-surface)")]
    rows += [(f"shadow-{k}", v) for k, v in t["elevation"].items()]
    rows += [("shadow", "var(--shadow-low)")]
    m = t["motion"]
    rows += [("motion-fast", m["duration"]["fast"]), ("motion-live", m["duration"]["live"]),
             ("motion-ease", m["easing"]), ("motion-press-scale", m["press_scale"]),
             ("focus-ring", t["layout"]["focus_ring"])]
    return [f"  --{k}: {v};" for k, v in rows]


BASE = """
body {
  margin: 0;
  background: var(--color-bg);
  color: var(--color-text);
  font-family: var(--font-sans);
  font-size: var(--type-body-md-size);
  line-height: var(--type-body-md-line);
  font-variant-numeric: tabular-nums;
}
a { color: var(--color-accent-text); }
code, .mono { font-family: var(--font-mono); }
:focus-visible { outline: 2px solid var(--color-accent); outline-offset: 2px; }
input, button {
  font: inherit;
  color: var(--color-text);
  background: var(--color-surface);
  border: 1px solid var(--color-border);
  border-radius: var(--radius-surface);
  padding: var(--space-sm) var(--space-md);
}
button {
  border-radius: var(--radius-control);
  cursor: pointer;
  transition: transform var(--motion-fast) var(--motion-ease);
}
button:active { transform: scale(var(--motion-press-scale)); }
.card {
  background: var(--glass-bg);
  -webkit-backdrop-filter: blur(var(--glass-blur));
  backdrop-filter: blur(var(--glass-blur));
  border: 1px solid var(--color-border);
  border-radius: var(--radius-surface);
  box-shadow: var(--shadow-low);
  padding: var(--space-lg);
}
"""


def build_css(t: dict) -> str:
    dark, light = mode_vars(t, "dark"), mode_vars(t, "light")
    out = [
        "/* GENERATED by scripts/build_tokens.py from design/tokens.json. Do not edit by hand. */",
        "/* Soft Liquid Minimal, indigo accent. Dark is the default; light follows the OS or [data-theme=light]. */",
        ":root {", *dark, *shared_vars(t), "}",
        "@media (prefers-color-scheme: light) {", '  :root:not([data-theme="dark"]) {',
        *["  " + r for r in light], "  }", "}",
        ':root[data-theme="light"] {', *light, "}",
        "@media (prefers-reduced-motion: reduce) {",
        "  :root { --motion-fast: 0ms; --motion-live: 0ms; }", "}",
    ]
    return "\n".join(out) + "\n" + BASE


def main(argv: list[str]) -> int:
    css = build_css(json.loads(SRC.read_text(encoding="utf-8")))
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != css:
            print("tokens.css is stale: run python scripts/build_tokens.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(css, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
